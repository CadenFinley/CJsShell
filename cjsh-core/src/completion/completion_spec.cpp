constexpr const char kHeaderPrefix[] = "generated by cjsh from man page for ";
constexpr const char kFormatPrefix[] = "format: ";
constexpr const char kSummaryPrefix[] = "summary: ";
constexpr const char kPathPrefix[] = "path: ";

std::mutex g_provider_mutex;
std::unordered_map<std::string, DynamicCompletionProvider> g_dynamic_providers;
std::unordered_map<std::string, CommandDoc> g_registered_docs;

std::string normalize_provider_name(const std::string& name) {
    std::string normalized;
    normalized.reserve(name.size());
    for (char ch : name) {
        unsigned char uch = static_cast<unsigned char>(ch);
        if (std::isalnum(uch) != 0 || ch == '-' || ch == '_' || ch == '.') {
            normalized.push_back(static_cast<char>(std::tolower(uch)));
        }
    }
    return normalized;
}

std::string normalize_command_name(std::string name) {
    std::transform(name.begin(), name.end(), name.begin(),
                   [](unsigned char ch) { return static_cast<char>(std::tolower(ch)); });
    return name;
}

std::string encode_field(const std::string& value) {
    std::ostringstream encoded;
    encoded << std::uppercase << std::hex;
    for (unsigned char ch : value) {
        if (ch == '%' || ch == ',' || ch == '\t' || ch == '\n' || ch == '\r') {
            encoded << '%' << std::setw(2) << std::setfill('0') << static_cast<unsigned int>(ch);
        } else {
            encoded << static_cast<char>(ch);
        }
    }
    return encoded.str();
}

int hex_value(char ch) {
    if (ch >= '0' && ch <= '9')
        return ch - '0';
    if (ch >= 'a' && ch <= 'f')
        return 10 + ch - 'a';
    if (ch >= 'A' && ch <= 'F')
        return 10 + ch - 'A';
    return -1;
}

std::optional<std::string> decode_field(const std::string& value) {
    std::string decoded;
    decoded.reserve(value.size());
    for (std::size_t index = 0; index < value.size(); ++index) {
        if (value[index] != '%') {
            decoded.push_back(value[index]);
            continue;
        }
        if (index + 2 >= value.size())
            return std::nullopt;
        int high = hex_value(value[index + 1]);
        int low = hex_value(value[index + 2]);
        if (high < 0 || low < 0)
            return std::nullopt;
        decoded.push_back(static_cast<char>((high << 4) | low));
        index += 2;
    }
    return decoded;
}

std::string encode_list(const std::vector<std::string>& values) {
    std::ostringstream stream;
    for (std::size_t index = 0; index < values.size(); ++index) {
        if (index != 0)
            stream << ',';
        stream << encode_field(values[index]);
    }
    return stream.str();
}

std::optional<std::vector<std::string>> decode_list(const std::string& value) {
    std::vector<std::string> result;
    if (value.empty())
        return result;

    std::size_t start = 0;
    while (start <= value.size()) {
        std::size_t comma = value.find(',', start);
        std::string encoded =
            value.substr(start, comma == std::string::npos ? std::string::npos : comma - start);
        auto decoded = decode_field(encoded);
        if (!decoded.has_value())
            return std::nullopt;
        result.push_back(std::move(*decoded));
        if (comma == std::string::npos)
            break;
        start = comma + 1;
    }
    return result;
}

std::vector<std::string> split_tabs(const std::string& line) {
    std::vector<std::string> fields;
    std::size_t start = 0;
    while (start <= line.size()) {
        std::size_t tab = line.find('\t', start);
        fields.push_back(
            line.substr(start, tab == std::string::npos ? std::string::npos : tab - start));
        if (tab == std::string::npos)
            break;
        start = tab + 1;
    }
    return fields;
}

EntryKind entry_kind_from_code(const std::string& value) {
    if (value == "S")
        return EntryKind::Subcommand;
    if (value == "P")
        return EntryKind::Positional;
    return EntryKind::Option;
}

char entry_kind_code(EntryKind kind) {
    switch (kind) {
        case EntryKind::Subcommand:
            return 'S';
        case EntryKind::Positional:
            return 'P';
        case EntryKind::Option:
        default:
            return 'O';
    }
}

ValueRequirement parse_requirement(const std::string& value) {
    if (value == "required")
        return ValueRequirement::Required;
    if (value == "optional")
        return ValueRequirement::Optional;
    return ValueRequirement::None;
}

ValueType parse_value_type(const std::string& value) {
    if (value == "text")
        return ValueType::Text;
    if (value == "file")
        return ValueType::File;
    if (value == "directory")
        return ValueType::Directory;
    if (value == "enum")
        return ValueType::Enum;
    if (value == "command")
        return ValueType::Command;
    if (value == "branch")
        return ValueType::Branch;
    if (value == "process")
        return ValueType::Process;
    if (value == "custom")
        return ValueType::Custom;
    return ValueType::None;
}

ValueSeparator parse_separator(const std::string& value) {
    if (value == "equals")
        return ValueSeparator::Equals;
    if (value == "either")
        return ValueSeparator::Either;
    return ValueSeparator::Space;
}

bool parse_bool(const std::string& value) {
    return value == "1" || value == "true" || value == "yes";
}

std::size_t parse_index(const std::string& value) {
    if (value.empty())
        return 0;
    try {
        std::size_t consumed = 0;
        unsigned long parsed = std::stoul(value, &consumed, 10);
        if (consumed != value.size())
            return 0;
        return static_cast<std::size_t>(parsed);
    } catch (...) {
        return 0;
    }
}

CompletionEntry* find_subcommand(std::vector<CompletionEntry>& entries, const std::string& name) {
    auto it = std::find_if(entries.begin(), entries.end(), [&](const CompletionEntry& entry) {
        return entry.kind == EntryKind::Subcommand && entry_matches_token(entry, name);
    });
    return it == entries.end() ? nullptr : &*it;
}

void serialize_entries(std::ostringstream& stream, const std::vector<CompletionEntry>& entries,
                       std::vector<std::string>& scope) {
    for (const auto& entry : entries) {
        stream << "E\t" << entry_kind_code(entry.kind) << '\t' << encode_list(scope) << '\t'
               << encode_field(entry.text) << '\t' << encode_field(entry.description) << '\t'
               << encode_list(entry.aliases) << '\t'
               << value_requirement_name(entry.value.requirement) << '\t'
               << value_type_name(entry.value.type) << '\t' << encode_field(entry.value.name)
               << '\t' << encode_list(entry.value.choices) << '\t' << encode_list(entry.conflicts)
               << '\t' << encode_list(entry.dependencies) << '\t' << (entry.repeatable ? '1' : '0')
               << '\t' << (entry.deprecated ? '1' : '0') << '\t'
               << encode_field(entry.value.dynamic_provider) << '\t' << entry.positional_index
               << '\t' << (entry.variadic ? '1' : '0') << '\t'
               << value_separator_name(entry.value.separator) << '\n';

        if (entry.kind == EntryKind::Subcommand && !entry.children.empty()) {
            scope.push_back(entry.text);
            serialize_entries(stream, entry.children, scope);
            scope.pop_back();
        }
    }
}

