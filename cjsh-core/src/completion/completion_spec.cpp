std::string serialize_command_doc(const std::string& command, const CommandDoc& doc) {
    std::ostringstream stream;
    stream << kHeaderPrefix << command << '\n';
    stream << kFormatPrefix << kCompletionSpecFormatVersion << '\n';
    stream << kSummaryPrefix << encode_field(doc.summary) << '\n';
    stream << kPathPrefix << encode_field(doc.executable_path) << '\n';
    std::vector<std::string> scope;
    serialize_entries(stream, doc.entries, scope);
    return stream.str();
}

std::optional<CommandDoc> parse_command_doc(const std::string& command,
                                            const std::string& contents) {
    std::istringstream stream(contents);
    std::string line;
    if (!std::getline(stream, line) || line != std::string(kHeaderPrefix) + command)
        return std::nullopt;

    CommandDoc doc;
    unsigned int format_version = 1;
    struct PendingEntry {
        std::vector<std::string> scope;
        CompletionEntry entry;
    };
    std::vector<PendingEntry> pending;

    while (std::getline(stream, line)) {
        if (line.empty())
            continue;
        if (line.rfind(kFormatPrefix, 0) == 0) {
            format_version = static_cast<unsigned int>(
                parse_index(line.substr(std::char_traits<char>::length(kFormatPrefix))));
            if (format_version == 0 || format_version > kCompletionSpecFormatVersion)
                return std::nullopt;
            continue;
        }
        if (line.rfind(kSummaryPrefix, 0) == 0) {
            std::string raw = line.substr(std::char_traits<char>::length(kSummaryPrefix));
            auto value = format_version >= 2 ? decode_field(raw)
                                             : std::optional<std::string>(std::move(raw));
            if (!value.has_value())
                return std::nullopt;
            doc.summary = std::move(*value);
            doc.summary_present = true;
            continue;
        }
        if (line.rfind(kPathPrefix, 0) == 0) {
            std::string raw = line.substr(std::char_traits<char>::length(kPathPrefix));
            auto value = format_version >= 2 ? decode_field(raw)
                                             : std::optional<std::string>(std::move(raw));
            if (!value.has_value())
                return std::nullopt;
            doc.executable_path = std::move(*value);
            continue;
        }

        auto fields = split_tabs(line);
        if (fields.size() >= 18 && fields[0] == "E") {
            auto scope = decode_list(fields[2]);
            auto text = decode_field(fields[3]);
            auto description = decode_field(fields[4]);
            auto aliases = decode_list(fields[5]);
            auto value_name = decode_field(fields[8]);
            auto choices = decode_list(fields[9]);
            auto conflicts = decode_list(fields[10]);
            auto dependencies = decode_list(fields[11]);
            auto provider = decode_field(fields[14]);
            if (!scope || !text || !description || !aliases || !value_name || !choices ||
                !conflicts || !dependencies || !provider) {
                return std::nullopt;
            }

            CompletionEntry entry;
            entry.kind = entry_kind_from_code(fields[1]);
            entry.text = std::move(*text);
            entry.description = std::move(*description);
            entry.aliases = std::move(*aliases);
            entry.value.requirement = parse_requirement(fields[6]);
            entry.value.type = parse_value_type(fields[7]);
            entry.value.name = std::move(*value_name);
            entry.value.choices = std::move(*choices);
            entry.conflicts = std::move(*conflicts);
            entry.dependencies = std::move(*dependencies);
            entry.repeatable = parse_bool(fields[12]);
            entry.deprecated = parse_bool(fields[13]);
            entry.value.dynamic_provider = std::move(*provider);
            entry.positional_index = parse_index(fields[15]);
            entry.variadic = parse_bool(fields[16]);
            entry.value.separator = parse_separator(fields[17]);
            pending.push_back({std::move(*scope), std::move(entry)});
            continue;
        }

        // Version 1 compatibility: <O|S|P> TAB value TAB description.
        if (fields.size() >= 3 && fields[0].size() == 1) {
            CompletionEntry entry;
            entry.kind = entry_kind_from_code(fields[0]);
            entry.text = fields[1];
            entry.description = fields[2];
            entry.repeatable = true;  // The old format had no repeatability semantics.
            pending.push_back({{}, std::move(entry)});
        }
    }

    std::stable_sort(pending.begin(), pending.end(),
                     [](const PendingEntry& lhs, const PendingEntry& rhs) {
                         return lhs.scope.size() < rhs.scope.size();
                     });
    for (auto& item : pending) {
        std::vector<CompletionEntry>* entries = &doc.entries;
        bool valid_scope = true;
        for (const auto& component : item.scope) {
            CompletionEntry* parent = find_subcommand(*entries, component);
            if (parent == nullptr) {
                valid_scope = false;
                break;
            }
            entries = &parent->children;
        }
        if (valid_scope)
            entries->push_back(std::move(item.entry));
    }

    doc.summary_present = true;
    return doc;
}

